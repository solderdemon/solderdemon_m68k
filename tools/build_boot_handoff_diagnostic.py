"""Generate an isolated IC2 experiment: end ROM overlay on a high-ROM read.

Does not count AS edges during vector fetch. Intended only for ROM firmware
whose reset PC is in E00000-EFFFFF. No physical timing claim is made.
"""
from pathlib import Path
import random
import sys
import zipfile

import cupl


ROOT = Path(__file__).resolve().parents[1] / 'code/firmware/pld/cpld'
OUT = ROOT / 'diagnostics/boot_handoff'
LEGACY = ROOT / 'diagnostics/legacy_as_counter'


def pins(dev, address=0):
    p = {n: 0 for n in dev.pins.values()}
    p.update(HALT=1, RESET=1, HWRST=0, AS=0, RW=1, LGEXP=1, FC2=1, FC0=1)
    for bit in (19, 20, 21, 22, 23):
        p[f'A{bit}'] = address >> bit & 1
    return p


def generate():
    OUT.mkdir(parents=True, exist_ok=True)
    baseline = LEGACY if LEGACY.exists() else ROOT
    source = (baseline / 'ic2_decoder.pld').read_text()
    source = source.replace('PINNODE = [BQ0..2];                 /* boot counter */\n', '')
    marker = '/* BOOT is cleared while RESET and HALT are both asserted'
    assert source.count(marker) == 1
    candidate = source.split(marker)[0] + '''/* Diagnostic experiment: keep the ROM overlay throughout reset-vector
   reads. End it after the first normal read in E00000-EFFFFF, where the
   existing firmware is linked. Extra AS edges at low addresses do not
   advance a counter. BOOT stays set until external RESET+HALT. */
running = HALT # RESET;
highrom = A23 & A22 & A21 & !A20;
BOOT.d  = running & (BOOT # (ANYIACK & RW & highrom));
BOOT.ck = AS;
BOOT.ar = !HALT & !RESET;
'''
    assert 'BQ0' not in candidate and 'BQ1' not in candidate and 'BQ2' not in candidate
    original = cupl.Device((baseline / 'ic2_decoder.pld').read_text())
    dev = cupl.Device(candidate)

    # Any number of extra low-address AS edges must leave the vector ROM mapped.
    for initial in (0, 1):
        q = {'BOOT': initial}
        p = pins(dev); p.update(HALT=0, RESET=0, HWRST=1)
        dev.outputs(p, q)
        assert q == {'BOOT': 0}
        for extra in range(65):
            for address in (0, 2, 4, 6):
                p = pins(dev, address)
                for _ in range(extra + 1):
                    o = dev.outputs(p, q)
                    assert o['EVENROMSEL'] == o['ODDROMSEL'] == 0
                    assert o['EVENRAMSEL'] == o['ODDRAMSEL'] == 1
                    q = dev.clock_edge(p, q, {'AS'})
                    assert q['BOOT'] == 0
        p = pins(dev, 0xE00404)
        assert dev.outputs(p, q)['EVENROMSEL'] == 0
        q = dev.clock_edge(p, q, {'AS'})
        assert q['BOOT'] == 1
        p = pins(dev, 0)
        o = dev.outputs(p, q)
        assert o['EVENRAMSEL'] == o['ODDRAMSEL'] == 0
        assert o['EVENROMSEL'] == o['ODDROMSEL'] == 1

    # Memory decoding itself remains identical at either value of BOOT.
    rng = random.Random(1)
    for _ in range(20000):
        p = {n: rng.getrandbits(1) for n in original.pins.values()}
        boot = rng.getrandbits(1)
        q_old = {r: rng.getrandbits(1) for r in original.regs}; q_old['BOOT'] = boot
        assert original.outputs(p, q_old) == dev.outputs(p, {'BOOT': boot})
    # Demonstrate the hypothesized failure with one extra vector AS edge.
    q_old = original.reset_state(); p = pins(original)
    for _ in range(4):
        q_old = original.clock_edge(p, q_old, {'AS'})
    assert original.outputs(p, q_old)['EVENRAMSEL'] == 0
    print('PASS: extra low-address edges do not remove vector ROM; high-ROM read ends overlay.')
    print('PASS: 20,000 random decode vectors agree at the same BOOT state.')
    print('Model reproduces early RAM selection after an extra AS edge in the original counter.')
    (OUT / 'ic2_decoder.pld').write_text(candidate)
    (OUT / 'ic3_glue.pld').write_bytes((ROOT / 'ic3_glue.pld').read_bytes())
    (OUT / 'build.sh').write_text((ROOT / 'build.sh').read_text().replace('python - ', 'python3 - '))
    (OUT / 'README.md').write_text('''# Boot-handoff experiment

Generated by tools/build_boot_handoff_diagnostic.py.
This is an unconfirmed diagnostic hypothesis, not a proven repair.

IC2 replaces the four-AS-edge boot counter with a sticky BOOT register set
at the end of the first normal read in E00000-EFFFFF. This requires the
reset PC to point into high ROM, as the existing rosco firmware linker does.
The low-address vector ROM cannot disappear due solely to extra low-address
AS edges. No wait states are added. All external pins retain their assignments.

IC3 in this experiment is the ORIGINAL production image, not reset_guard.
Build with bash build.sh; check the fit with check_startup_fit.py pointing
at this directory. The original checker still compares production sources
against GALs; this experiment intentionally changes BOOT timing.

For an isolated hardware test, program IC2_TEST.jed into IC2 and
IC3_ORIGINAL.jed into IC3. Verify both. ROM Flash contents remain unchanged.
Rollback IC2 using IC2_ROLLBACK.jed. Do not exchange these chip assignments.

Source-model checks cover reset from both BOOT states, up to 64 extra AS
edges per vector word, high-ROM handoff, RAM selection and 20,000 random
decode vectors. These checks do not prove that AS ringing occurs on the board,
or that timing, voltage or physical connections are correct.
''')
    print(OUT)


def package():
    paths = {'IC2_TEST.jed': OUT / 'bin/ic2_decoder.jed',
             'IC3_ORIGINAL.jed': ROOT / 'bin/ic3_glue.jed',
             'IC2_ROLLBACK.jed': (LEGACY if LEGACY.exists() else ROOT) / 'bin/ic2_decoder.jed',
             'ic2_decoder.pld': OUT / 'ic2_decoder.pld',
             'ic2_decoder.fit': OUT / 'bin/ic2_decoder.fit',
             'README.md': OUT / 'README.md'}
    target = OUT / 'solderdemon_m68k-boot-handoff-test.zip'
    with zipfile.ZipFile(target, 'w', zipfile.ZIP_DEFLATED) as z:
        for name, path in paths.items():
            z.writestr(name, path.read_bytes())
    print(target)


if __name__ == '__main__':
    if sys.argv[1:] == ['--package']:
        package()
    elif not sys.argv[1:]:
        generate()
    else:
        raise SystemExit('Usage: build_boot_handoff_diagnostic.py [--package]')
