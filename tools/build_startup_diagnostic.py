"""Generate an isolated reset-guard experiment; never overwrite production PLDs/JEDs.

python3 tools/build_startup_diagnostic.py
Then run code/firmware/pld/cpld/diagnostics/reset_guard/build.sh (Docker required).
"""
from pathlib import Path
import hashlib
import itertools
import random
import sys
import zipfile

import cupl


def main():
    root = Path(__file__).resolve().parents[1] / 'code/firmware/pld/cpld'
    out = root / 'diagnostics/reset_guard'
    out.mkdir(parents=True, exist_ok=True)
    original = (root / 'ic3_glue.pld').read_text()
    old = "BERR.oe = PBERR;"
    assert original.count(old) == 1
    changed = original.replace(old, """/* Diagnostic experiment: deterministic watchdog reset; not a proven fix.
   HWRST affects only the watchdog here. Normal operation is unchanged. */
[AX4M, AX2M, AX1M].ar = HWRST;
[WDQ0..3].ar = HWRST;
PBERR.ar = HWRST;
BERR.oe = PBERR & !HWRST;""")
    baseline, candidate = cupl.Device(original), cupl.Device(changed)
    rng = random.Random(1)
    for _ in range(20000):
        p = {n: rng.getrandbits(1) for n in baseline.pins.values()}
        p['HWRST'] = 0
        q = {r: rng.getrandbits(1) for r in baseline.regs}
        assert baseline.outputs(p, dict(q)) == candidate.outputs(p, dict(q))
        assert baseline.clock_edge(p, dict(q), {'CLK'}) == candidate.clock_edge(p, dict(q), {'CLK'})
    for bits in itertools.product((0, 1), repeat=len(candidate.regs)):
        for as_level in (0, 1):
            p = {n: 1 for n in candidate.pins.values()}
            p.update(HWRST=1, AS=as_level)
            q = dict(zip(candidate.regs, bits))
            signals = candidate.outputs(p, q)
            assert not any(q.values()), q
            assert signals['BERR'] is None
            assert signals['RESET'] == signals['HALT'] == 0
    (out / 'ic2_decoder.pld').write_bytes((root / 'ic2_decoder.pld').read_bytes())
    (out / 'ic3_glue.pld').write_text(changed)
    (out / 'build.sh').write_text((root / 'build.sh').read_text().replace('python - ', 'python3 - '))
    (out / 'build.sh').chmod(0o755)
    digest = hashlib.sha256((root / 'bin/ic3_glue.jed').read_bytes()).hexdigest()
    (out / 'README.md').write_text(f"""# Reset-guard diagnostic experiment

Generated by `tools/build_startup_diagnostic.py`. This is an experiment,
not a confirmed repair. Production sources and JEDs remain unchanged.

IC2 is unchanged. IC3 adds asynchronous HWRST clear to the eight watchdog
registers and disables BERR while HWRST is high. It does not add memory wait states
or change DUART initialization, addresses, reset duration or pin assignments.

Source-model checks: 20,000 random vectors agree with the baseline when HWRST=0;
all 256 watchdog states clear with HWRST=1 for either AS level, without clock edges.

Build from this directory with `bash build.sh`, then from the mainboard directory:

```
python3 tools/check_startup_fit.py code/firmware/pld/cpld/diagnostics/reset_guard
```

Only after both commands pass, program **IC3** using `bin/ic3_glue.jed` in this
directory and run the programmer's Verify operation. Keep IC2 unchanged.
Compare repeated cold starts and resets before/after under the same conditions.
Record full start, RUN without UART, or no RUN. A failed experiment does not
exclude other CPLD timing problems. Restore the production IC3 JED for rollback.

Production rollback file: `../../bin/ic3_glue.jed`
SHA-256 at generation: `{digest}`

The ZIP package uses explicit names: program `ic3_reset_guard_TEST.jed` into
IC3 only; `ic3_original_ROLLBACK.jed` restores the production IC3 image.
Do not program either file into IC2. ROM Flash contents are unchanged.
After both builds and fit checks pass, generate the archive with:
`python3 tools/build_startup_diagnostic.py --package` (from mainboard root).
""")
    print('PASS: 20,000 normal-operation vectors and 512 reset cases.')
    print(f'Generated isolated diagnostic sources: {out}')


def package():
    root = Path(__file__).resolve().parents[1] / 'code/firmware/pld/cpld'
    out = root / 'diagnostics/reset_guard'
    files = {
        'ic3_reset_guard_TEST.jed': out / 'bin/ic3_glue.jed',
        'ic3_original_ROLLBACK.jed': root / 'bin/ic3_glue.jed',
        'ic3_glue.pld': out / 'ic3_glue.pld',
        'ic3_glue.fit': out / 'bin/ic3_glue.fit',
        'README.md': out / 'README.md',
    }
    checksum_lines = []
    target = out / 'solderdemon_m68k-ic3-reset-guard-test.zip'
    with zipfile.ZipFile(target, 'w', zipfile.ZIP_DEFLATED) as archive:
        for name, path in files.items():
            content = path.read_bytes()
            archive.writestr(name, content)
            checksum_lines.append(f'{hashlib.sha256(content).hexdigest()}  {name}')
        archive.writestr('SHA256SUMS.txt', '\n'.join(checksum_lines) + '\n')
    print(target)


if __name__ == '__main__':
    if sys.argv[1:] == ['--package']:
        package()
    elif not sys.argv[1:]:
        main()
    else:
        raise SystemExit('Usage: build_startup_diagnostic.py [--package]')
